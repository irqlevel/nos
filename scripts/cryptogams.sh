#!/bin/sh
# The assembly the crypto crate is built with, made from CRYPTOGAMS' perlasm
# in src/crates/base/crypto/cryptogams -- kept there as it came, at the
# commit its README names -- into src/crates/base/crypto/src/asm.
#
#   scripts/cryptogams.sh           write the .s files
#   scripts/cryptogams.sh --check   make them in a scratch directory and
#                                   compare with the ones in the tree:
#                                   `make check`'s, so that what is built is
#                                   what the sources say, and nobody's edit
#
# Needs perl and clang: the nos-builder image has both, and so does a Mac.
#
# Each source is run in its kernel mode: no OPENSSL_ia32cap_P or
# OPENSSL_armcap_P read -- the caller picks the code path, each one an
# entry point of its own -- and on arm64 the C preprocessor's __KERNEL__.
# perlasm decides which AVX levels to emit by the C compiler's version: it
# is told a clang 6's, which gives AVX and AVX2 and no AVX-512, whatever
# compiler there is here, so the output is the same on every machine.
# x86-64's translator ends a file with a GNU property note (CET's), which
# is left out: a note is nothing the kernel's linker script places. arm64's
# is made twice: for ELF (the kernel, and a Linux host's fuzzers) and for
# Mach-O (a Mac's), each Mach-O file one atom (one_atom, below). A file's
# local labels are given its name -- `.Loop`
# becomes `.Lpoly1305_Loop` -- since the crate assembles its files as one
# (global_asm!) and two of them have a `.Loop`: only the labels a file
# defines, renamed as whole words, nothing else of the code touched. Each
# file starts with the CRYPTOGAMS license, which a copy of its source
# carries.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC=$ROOT/src/crates/base/crypto/cryptogams
DST=$ROOT/src/crates/base/crypto/src/asm
CLANG=${CLANG:-clang}

CHECK=0
case "${1:-}" in
    --check) CHECK=1 ;;
    "") ;;
    *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

for tool in perl "$CLANG"; do
    command -v "$tool" > /dev/null || { echo "$0: $tool is needed" >&2; exit 1; }
done

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir "$TMP/out"

# The compiler perlasm asks the version of.
printf '#!/bin/sh\necho "clang version 6.0.0"\n' > "$TMP/cc"
chmod +x "$TMP/cc"

# $2's local labels -- ELF's `.L` ones, Mach-O's `L` ones -- given the name
# $3, into $1: every label the file defines, and every use of one.
own_labels() {
    perl -e '
        my ($in, $tag) = @ARGV;
        open my $f, "<", $in or die "$in: $!";
        my $text = do { local $/; <$f> };
        my %defined;
        $defined{$1} = 1 while $text =~ /^(\.?L[A-Za-z0-9_\$]+):/mg;
        if (%defined) {
            my $any = join "|", map { quotemeta } sort { length $b <=> length $a } keys %defined;
            $text =~ s{(?<![A-Za-z0-9_.\$])($any)(?![A-Za-z0-9_\$])}{
                my $l = $1;
                $l =~ /^\./ ? ".L${tag}_" . substr($l, 1) : "L${tag}_$l"
            }ge;
        }
        print $text;
    ' "$2" "$3" > "$1"
}

# Mach-O's $2 made one atom, into $1. A Mach-O object is split at each
# symbol that is not an assembler-local `L` one into atoms the linker places
# -- and with -dead_strip, which Rust links a Mac's programs with, drops --
# one by one; but a conditional branch or an ADR from one into another has
# no relocation, and the assembler resolves it as the object lays them out.
# ChaCha20_neon's branch to the 512-byte path in ChaCha20_512_neon's atom
# landed in Poly1305 once that atom was dropped, and returned with its
# frame still pushed. So: every label but a global one made local (`L` and
# the file's name), a label at the top the one atom starts at, and each
# global symbol an alternate entry into it (`.alt_entry`).
one_atom() {
    perl -e '
        my ($in, $tag) = @ARGV;
        open my $f, "<", $in or die "$in: $!";
        my $text = do { local $/; <$f> };
        my %global;
        $global{$1} = 1 while $text =~ /^\s*\.globl\s+(\S+)/mg;
        my %helper;
        while ($text =~ /^([A-Za-z_][A-Za-z0-9_]*):/mg) {
            my $name = $1;
            $helper{$name} = 1 unless $global{$name} || $name =~ /^L/;
        }
        if (%helper) {
            my $any = join "|", map { quotemeta } sort { length $b <=> length $a } keys %helper;
            $text =~ s{(?<![A-Za-z0-9_.\$])($any)(?![A-Za-z0-9_\$])}{L${tag}_$1}g;
        }
        $text =~ s{^(\s*\.text[ \t]*\n)}{$1cryptogams_${tag}:\n}m or die "$in: no .text";
        for my $g (sort keys %global) {
            $text =~ s{^(\Q$g\E:)}{.alt_entry $g\n$1}m or die "$in: $g is never defined";
        }
        print $text;
    ' "$2" "$3" > "$1"
}

# The license, as a comment, ahead of what $2 holds, into $1.
with_license() {
    {
        printf '/*\n'
        printf ' * Generated by scripts/cryptogams.sh from cryptogams/%s -- do not edit.\n' "$3"
        printf ' *\n'
        printf ' * CRYPTOGAMS by Andy Polyakov, https://github.com/dot-asm/cryptogams, under\n'
        printf ' * the license below (cryptogams/LICENSE), the BSD-style one of its two:\n'
        printf ' *\n'
        sed -e 's/[[:space:]]*$//' -e 's/^/ * /' -e 's/^ \* $/ */' "$SRC/LICENSE"
        printf ' */\n'
        cat "$2"
    } > "$1"
}

for f in chacha poly1305; do
    CC="$TMP/cc" perl "$SRC/x86_64/$f-x86_64.pl" elf-kernel "$TMP/$f-x86_64.raw"
    sed '/^\.section[[:space:]]*\.note\.gnu\.property/,$d' "$TMP/$f-x86_64.raw" > "$TMP/$f-x86_64.s"
    own_labels "$TMP/$f-x86_64.own" "$TMP/$f-x86_64.s" $f
    with_license "$TMP/out/$f-x86_64-elf.s" "$TMP/$f-x86_64.own" "x86_64/$f-x86_64.pl"
done

for f in chacha poly1305; do
    for flavour in linux64 ios64; do
        case $flavour in
            linux64) target=aarch64-linux-gnu ;;
            ios64) target=arm64-apple-macos ;;
        esac
        perl "$SRC/arm/$f-armv8.pl" $flavour "$TMP/$f-$flavour.S"
        "$CLANG" --target=$target -E -P -D__KERNEL__ -x assembler-with-cpp \
            "$TMP/$f-$flavour.S" -o "$TMP/$f-$flavour.cpp"
        # The preprocessor's blank lines and trailing blanks, which one
        # clang need not leave as another does, made one way
        sed 's/[[:space:]]*$//' "$TMP/$f-$flavour.cpp" | cat -s > "$TMP/$f-$flavour.s"
        own_labels "$TMP/$f-$flavour.own" "$TMP/$f-$flavour.s" $f
        if [ $flavour = ios64 ]; then
            one_atom "$TMP/$f-$flavour.atom" "$TMP/$f-$flavour.own" $f
            mv "$TMP/$f-$flavour.atom" "$TMP/$f-$flavour.own"
        fi
        with_license "$TMP/out/$f-armv8-$flavour.s" "$TMP/$f-$flavour.own" "arm/$f-armv8.pl"
    done
done

if [ $CHECK = 1 ]; then
    status=0
    for made in "$TMP"/out/*.s; do
        name=$(basename "$made")
        if ! cmp -s "$made" "$DST/$name"; then
            echo "$0: $DST/$name is not what cryptogams/ makes: run $0" >&2
            status=1
        fi
    done
    for kept in "$DST"/*.s; do
        [ -e "$TMP/out/$(basename "$kept")" ] ||
            { echo "$0: $kept is made from nothing in cryptogams/" >&2; status=1; }
    done
    exit $status
fi

mkdir -p "$DST"
cp "$TMP"/out/*.s "$DST/"
ls -l "$DST"
