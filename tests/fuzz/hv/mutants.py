def digest(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def fresh_build_of_good():
    """Every file a mutant changes made newer than anything built of it:
    cargo rebuilds a crate by its files' times alone, so one last built with
    a mutant in it -- a run cut short, say -- whose good file came back with
    an older time would go on being built with the mutant."""
    for path in sorted({os.path.join(CRATES, m[2]) for m in MUTANTS}):
        os.utime(path, None)


def found_by(target):
    """Whether the target's gate finds something -- a finding or a hang --
    or None where the fuzzer does not build with the mutant in it: a mutant
    the compiler refuses holds no target to anything."""
    p = subprocess.run([sys.executable, FUZZ, '--target', target], cwd=ROOT, capture_output=True, text=True,
                       timeout=1800)
    if 'the build failed' in p.stdout:
        return None
    return p.returncode != 0


def main():
    wanted = set(sys.argv[1:])
    tried = 0
    missed = []
    fresh_build_of_good()
    for name, what, file, old, new, targets in MUTANTS:
        if wanted and name not in wanted:
            continue
        path = os.path.join(CRATES, file)
        with open(path) as f:
            good = f.read()
        good_digest = digest(path)
        tried += 1
        if good.count(old) != 1:
            print('BROKEN: %s -- its text is in %s %d times, not once' % (name, file, good.count(old)))
            missed.append(name)
            continue
        try:
            with open(path, 'w') as f:
                f.write(good.replace(old, new))
            by = None
            for t in targets:
                found = found_by(t)
                if found is None:
                    by = 'broken'
                    break
                if found:
                    by = t
                    break
            if by == 'broken':
                print('BROKEN: %s -- the mutant does not build' % name, flush=True)
                missed.append(name)
            elif by is None:
                print('SURVIVED: %s (%s)' % (name, what), flush=True)
                missed.append(name)
            else:
                print('CAUGHT: %s (%s) -- by %s' % (name, what, by), flush=True)
        finally:
            with open(path, 'w') as f:
                f.write(good)
            if digest(path) != good_digest:
                sys.exit('%s is not what it was: restore it from git' % path)
            os.utime(path, None)
    print('%d mutants, %d not caught%s' % (tried, len(missed), (': ' + ', '.join(missed)) if missed else ''))
    return 1 if missed else 0


if __name__ == '__main__':
    sys.exit(main())
