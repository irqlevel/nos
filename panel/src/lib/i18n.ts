const dictionaries: Record<Locale, Words> = { en, ru };

export function words(locale: Locale): Words {
  return dictionaries[locale];
}

/** A provider's text in `locale`: its descriptor's, or what there is. */
export type Text = Partial<Record<Locale, string>> | undefined;

export function text(t: Text, locale: Locale): string {
  return (t && (t[locale] || t.en || Object.values(t)[0])) || '';
}
